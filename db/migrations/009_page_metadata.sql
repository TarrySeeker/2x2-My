-- ============================================================
-- 009_page_metadata.sql — SEO-мета (title/description/keywords/OG) для страниц сайта
-- ============================================================
-- Этап CMS-перевода витрины (2026-04-24). Переносит hardcoded
-- `export const metadata` из `app/*/page.tsx` в БД, чтобы клиент
-- мог редактировать заголовки и описания страниц через админку
-- без передеплоя.
--
-- Почему отдельная таблица, а не расширение `seo_meta` (002_schema.sql):
--   1) `seo_meta` имеет структуру с `keywords TEXT` (строка через запятую)
--      и полями `og_title`/`og_description`/`schema_jsonld` — ориентирована
--      на тонкую настройку SEO SEO-специалистом.
--   2) Новая `page_metadata` проще: `keywords TEXT[]` (массив — удобно
--      для UI chip-input), плюс явное `canonical` и `noindex`. Нужна для
--      B2B-клиента, который просто хочет «поправить title главной».
--   3) Не ломаем существующий `seo_meta` — он остаётся резервом для
--      будущих задач (JSON-LD override, per-страница OG-tune).
--
-- Идемпотентно: CREATE TABLE IF NOT EXISTS, ON CONFLICT DO NOTHING
-- в seed. Повторный прогон не перезатрёт уже отредактированное.
--
-- RLS в проекте не применяется (self-hosted Postgres, см. db/README.md).
-- Авторизация — через requireAdmin() / requireRole() в Server Actions.
-- ============================================================

BEGIN;

-- ------------------------------------------------------------
-- 1. Таблица
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS page_metadata (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  path        TEXT NOT NULL UNIQUE,                 -- '/', '/about', '/services' ...
  title       TEXT NULL,                            -- `<title>` тег (full title, без шаблона)
  description TEXT NULL,                            -- meta description
  keywords    TEXT[] NOT NULL DEFAULT '{}',         -- массив ключевых слов
  og_image    TEXT NULL,                            -- path или полный URL
  noindex     BOOLEAN NOT NULL DEFAULT false,       -- robots: noindex, follow
  canonical   TEXT NULL,                            -- абсолютный URL, если отличается
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by  TEXT NULL                             -- users.id без FK (на случай удаления)
);

COMMENT ON TABLE page_metadata IS 'SEO-метаданные по страницам. Редактируется клиентом через /admin/seo. Переопределяет hardcoded metadata в app/*/page.tsx.';
COMMENT ON COLUMN page_metadata.path IS 'Относительный путь страницы (с ведущим /). Уникален.';
COMMENT ON COLUMN page_metadata.keywords IS 'Массив ключевых слов. TEXT[] (а не csv-строка) — чтобы UI отдавал chip-input.';
COMMENT ON COLUMN page_metadata.canonical IS 'Если задан — используется как <link rel="canonical">. Иначе — absoluteUrl(path).';

-- ------------------------------------------------------------
-- 2. Индексы
-- ------------------------------------------------------------
-- Уникальный индекс на path уже создан через UNIQUE constraint.
-- Дополнительный индекс для bulk-выборки (админка: «все страницы с noindex=true»)
CREATE INDEX IF NOT EXISTS idx_page_metadata_noindex
  ON page_metadata(noindex) WHERE noindex = true;

-- ------------------------------------------------------------
-- 3. Триггер updated_at (использует trg_update_updated_at из 003)
-- ------------------------------------------------------------
DROP TRIGGER IF EXISTS tr_page_metadata_updated ON page_metadata;
CREATE TRIGGER tr_page_metadata_updated
  BEFORE UPDATE ON page_metadata
  FOR EACH ROW EXECUTE FUNCTION trg_update_updated_at();

