-- ============================================================
-- 023_cleanup_promotions.sql — удаление мусорных записей в promotions
-- ============================================================
-- E2E-аудит (handoff e2e-admin-storefront-2026-04-26) обнаружил две
-- записи в `promotions`, которые подлежат удалению:
--
--   id = 5  : title = '[архив] 500 визиток или листовок в подарок (legacy id=5)',
--             is_active = false. Архивная legacy-запись от dedup-миграции
--             (007_promotions_dedup.sql), осталась как backup. Не отображается
--             на витрине, но засоряет /admin/content/promotions.
--
--   id = 11 : title = '500 визиток в подарокr' (опечатка `r` в конце),
--             slug = NULL, is_active = true. Дубль visitki-500 с битым
--             заголовком. Не отображается на витрине (фильтр или дедуп
--             отбрасывает из-за NULL slug), но засоряет админку.
--
-- Идемпотентно: DELETE с WHERE по id — повторный прогон будет no-op.
-- Ничего не удаляем, кроме явно перечисленных id, чтобы защититься
-- от случайного wipe'а.
-- ============================================================

BEGIN;

-- Удаление мусорных записей.
-- WHERE id IN (...) с дополнительной защитой по полям заголовка/slug,
-- чтобы случайно не задеть валидную запись, если кто-то перенумерует
-- id (маловероятно, но дёшево перестраховаться).

DELETE FROM promotions
WHERE id = 11
  AND (slug IS NULL OR slug = '')
  AND title ILIKE '%подарокr%';

DELETE FROM promotions
WHERE id = 5
  AND title LIKE '[архив]%';

COMMIT;
