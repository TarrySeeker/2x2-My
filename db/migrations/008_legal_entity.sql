-- ============================================================
-- 008_legal_entity.sql — юр. данные компании в site_settings
-- ============================================================
-- Клиентская правка 2026-04-24: понадобились юр. реквизиты для
-- страницы /privacy, футера и договоров.
--
-- Решение: новый JSONB-ключ `legal_entity` в таблице site_settings
-- (по аналогии с существующими contacts / business_hours / socials /
-- stats / seo_defaults / pd_consent). Отдельную колонку/таблицу
-- не создаём — меньше DDL, проще разложить в форме админки.
--
-- Поля (все опциональные, клиент заполнит сам через админку):
--   legal_name      — полное юр. название («ООО "Рекламное агентство 2х2"»)
--   inn             — ИНН (10 цифр для юрлиц, 12 для ИП)
--   ogrn            — ОГРН (13 цифр) или ОГРНИП (15 цифр)
--   kpp             — КПП (опционально, только для юрлиц, 9 знаков)
--   legal_address   — юр. адрес
--   actual_address  — фактический адрес (если отличается)
--   ceo_name        — ФИО директора (для договоров)
--   bank_account    — расчётный счёт (20 цифр)
--   bank_name       — название банка
--   bik             — БИК банка (9 цифр)
--
-- Идемпотентно: вставка через ON CONFLICT (key) DO NOTHING —
-- повторный прогон не перезатрёт уже введённые клиентом данные.
-- НЕ хардкодим реальные значения — все поля пустые строки.
--
-- Доступ:
--   - READ: публичный (сервер-компоненты footer/about/privacy читают
--     через getSetting('legal_entity') — кеш 60 сек, тег settings:legal_entity).
--   - WRITE: только через Server Action updateSiteSettingAction,
--     который защищён requireAdmin() (owner|manager). RLS в этом
--     проекте не используется (см. db/README.md — self-hosted
--     Postgres без Supabase, авторизация в Server Actions).
-- ============================================================

BEGIN;

-- ------------------------------------------------------------
-- Создаём ключ legal_entity с пустым дефолт-значением.
-- Структура JSONB — плоский объект строковых полей. Поля-строки,
-- а не NULL, чтобы форма в админке корректно подхватывала
-- defaultValues (чтобы input'ы были controlled, а не uncontrolled).
-- ------------------------------------------------------------
INSERT INTO site_settings (key, value) VALUES
  ('legal_entity', $$
    {
      "legal_name":     "",
      "inn":            "",
      "ogrn":           "",
      "kpp":            "",
      "legal_address":  "",
      "actual_address": "",
      "ceo_name":       "",
      "bank_account":   "",
      "bank_name":      "",
      "bik":            ""
    }
  $$::jsonb)
ON CONFLICT (key) DO NOTHING;

COMMIT;
