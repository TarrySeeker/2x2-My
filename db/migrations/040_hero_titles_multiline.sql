-- ============================================================
-- 040_hero_titles_multiline.sql — переразбить hero.titles на строки
-- ============================================================
-- Правка клиента 2026-05-09: вторая строка ротейтящегося title должна
-- быть чёрной, остальное — оранжевой. Логика рендера в
-- HeroSectionClient.tsx разбивает каждый title по `\n` и красит
-- вторую строку в text-brand-dark.
--
-- В БД сейчас оба title — однострочные. Добавляем разделители
-- так, чтобы получились 2-3 визуальные строки на ноутбуке/телефоне:
--
-- 1) "Региональный оператор\nнаружной рекламы\nХМАО и ЯНАО"
--    → строки: оранжевая | ЧЁРНАЯ | оранжевая
-- 2) "Мы создаём рекламу,\nкоторую замечают"
--    → строки: оранжевая | ЧЁРНАЯ
--
-- Заодно фиксим typewriter «2×2» (математический ×) → «2х2»
-- (кириллическая х) — пакет Г пропустил это значение в БД.
--
-- Идемпотентно: если новые значения уже стоят, jsonb_set перезапишет
-- их теми же значениями (no-op).
-- ============================================================

UPDATE homepage_sections
SET content = jsonb_set(
  jsonb_set(
    content,
    '{titles}',
    '[
      "Региональный оператор\nнаружной рекламы\nХМАО и ЯНАО",
      "Мы создаём рекламу,\nкоторую замечают"
    ]'::jsonb
  ),
  '{typewriter}',
  '"2х2, потому что с нами просто!"'::jsonb
)
WHERE key = 'hero';
