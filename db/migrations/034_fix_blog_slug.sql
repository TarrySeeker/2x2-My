-- ============================================================
-- 034_fix_blog_slug.sql — фикс опечатки в slug блог-поста
--
-- 014_blog_post_6.sql при создании поста «Оперативная печать или
-- офсет: что выбрать для своего тиража» использовал slug
-- 'operativnaya-pechtat-vs-ofsetnaya-chto-vybrat'.
-- Опечатка: 'pechtat' вместо 'pechat'.
--
-- В коде сайта тоже было 'pechtat' (везде согласовано), но снаружи
-- ссылка выглядит безграмотно — нашли при аудите 2026-05-08.
--
-- Безопасно: UPDATE применится только к постам, где такая опечатка
-- встречается. Если миграцию накатить дважды — второй раз ничего
-- не поменяется.
-- ============================================================

UPDATE blog_posts
SET slug = REPLACE(slug, 'pechtat', 'pechat')
WHERE slug LIKE '%pechtat%';
