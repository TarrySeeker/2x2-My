-- ============================================================
-- 041_user_role_manager.sql — переопределение роли `manager`
-- ============================================================
-- 2026-05-11. Бизнес-требование клиента: ввести «аккаунт менеджера»
-- с ОГРАНИЧЕННЫМ доступом к админке.
--
-- Что НЕ меняется в схеме:
--   * enum `user_role` уже содержит ('owner', 'manager', 'content')
--     с миграции 001_extensions_and_enums.sql — DDL не нужен.
--   * users.role уже NOT NULL DEFAULT 'manager'
--     (см. 004_lucia_auth.sql).
--
-- Что меняется:
--   1. Меняем DEFAULT для users.role с 'manager' на 'owner'. До этой
--      даты `manager` имел те же права, что и owner — поэтому DEFAULT
--      'manager' был безвреден. С 2026-05-11 manager — урезанная роль
--      (без услуг/контента/SEO/настроек/заявок), и для НОВОГО админа,
--      добавляемого без явного role, безопаснее давать owner.
--   2. Документируем новую семантику в комментарии к колонке.
--   3. Best-effort: если в БД есть пользователи, у которых явно стоит
--      role='manager' (наследие старого контракта, когда manager == owner),
--      их НЕ ПЕРЕВОДИМ автоматически — пусть владелец вручную решит,
--      какие из них должны остаться менеджерами (с урезанными правами),
--      а какие — стать owner. Если миграция применяется на пустой БД
--      или production без manager-аккаунтов, то этот raise notice
--      просто молча пропустится.
--
-- Roll-forward only. Откат: ALTER TABLE users ALTER COLUMN role
--   SET DEFAULT 'manager';
-- ============================================================

-- 1. Сменить DEFAULT.
ALTER TABLE users
  ALTER COLUMN role SET DEFAULT 'owner';

-- 2. Документировать новую семантику.
COMMENT ON COLUMN users.role IS
  'Роль в админ-панели (2026-05-11):
   • owner   — полный доступ ко всем разделам;
   • manager — ограниченный доступ: дашборд, промокоды, отзывы,
               блог, портфолио, команда, акции, категории портфолио.
               НЕ ВИДИТ: услуги, контент сайта, SEO, настройки, заявки.
   • content — только блог и контент сайта (CMS, портфолио, блог).
   Источник истины — lib/auth/permissions.ts.';

-- 3. Информативный NOTICE о существующих managers (не блокирует).
DO $$
DECLARE
  manager_count INT;
BEGIN
  SELECT COUNT(*) INTO manager_count FROM users WHERE role = 'manager';
  IF manager_count > 0 THEN
    RAISE NOTICE
      'Внимание: в БД есть % пользователей с role=manager. С 2026-05-11 роль manager имеет урезанные права. Если им нужен полный доступ, переведите в owner: UPDATE users SET role=''owner'' WHERE username=''<имя>'';',
      manager_count;
  END IF;
END $$;

