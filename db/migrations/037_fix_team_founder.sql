-- ============================================================
-- 037_fix_team_founder.sql — исправить «15 лет» в bio основателя
-- ============================================================
-- Проблема: в 027_team_seed.sql bio содержит «15 лет в наружной
-- рекламе ХМАО-Югры». Это не соответствует году основания 2014:
-- на 2026 год это 12 лет, а не 15. Мягкая формулировка «10+ лет»
-- уже использована в AboutStory и page_sections — приводим к единому
-- виду.
--
-- Идемпотентно: UPDATE по точному совпадению bio, повторный прогон
-- не меняет уже-обновлённую строку.
-- ============================================================

UPDATE team_members
SET bio = '10+ лет в наружной рекламе ХМАО-Югры. Основатель компании «2х2».'
WHERE
  (position ILIKE '%основатель%' OR role ILIKE '%основатель%' OR role = 'Руководитель')
  AND bio LIKE '%15 лет%';
