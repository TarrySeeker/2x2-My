-- ============================================================
-- 035_fix_about_dates.sql — фикс несостыковки дат /about
--
-- 010_page_sections.sql закладывал в page_sections для /about → story
-- год основания 2011 и «15 лет» — но в JSON-LD (lib/seo/site.ts
-- BUSINESS.foundingYear) уже стоял 2014. Фронт читает page_sections
-- через CMS, поэтому пользователь видел противоречие.
--
-- Этой миграцией обновляем JSON в БД, чтобы соответствовало
-- 2014-му году и формулировке "10+ лет".
--
-- Безопасность: UPDATE затрагивает ОДНУ строку (page_path='/about',
-- section_key='story'). Если контент-менеджер уже отредактировал
-- секцию вручную — миграция перезапишет (это и нужно для синхронизации,
-- иначе несоответствие останется).
--
-- НЕ ОТКАТЫВАЕМ автоматически — если вернуться к старым датам
-- понадобится, поправят руками или новой миграцией.
-- ============================================================

UPDATE page_sections
SET content = jsonb_set(
  jsonb_set(
    jsonb_set(
      content,
      '{paragraphs}',
      to_jsonb(ARRAY[
        'Агентство 2×2 основано в 2014 году партнёрами с многолетним опытом. Начинали с небольшой студии полиграфии, но быстро поняли: клиентам нужен комплексный подход.',
        'Сегодня мы — команда из 7 специалистов: дизайнеры, технологи, монтажники.',
        'За 10+ лет реализовали более 500 проектов — от визиток до брендирования масштабных работ.'
      ])
    ),
    '{stats}',
    '[
      {"value": "2014", "label": "год основания"},
      {"value": "7+",   "label": "специалистов в команде"},
      {"value": "10+",  "label": "лет на рынке ХМАО"}
    ]'::jsonb
  ),
  '{updated_marker}',
  '"2026-05-08-fix-dates"'::jsonb
)
WHERE page_path = '/about' AND section_key = 'story';
