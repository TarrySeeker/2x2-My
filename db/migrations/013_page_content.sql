--   version — инкремент при редактировании (audit / changelog)
--   published — false → страница возвращает 404
--
-- НЕ путать с:
--   * `pages` (002_schema.sql) — старая "CMS для магазина", CRUD-страницы
--     типа /delivery, /warranty. Оставляем, не трогаем.
--   * `page_sections` (миграция 010) — структурный JSONB для страниц с
--     несколькими секциями. Privacy — одно большое полотно текста,
--     JSONB тут избыточен.
--
-- Seed: берём текущий текст из app/privacy/page.tsx как есть и
-- перегоняем в markdown. Плейсхолдеры для реквизитов ({legal_name},
-- {inn}, {ogrn}, {legal_address}, {actual_address}) — подставляются
-- рантаймом из site_settings.legal_entity.
--
-- Рантаймовая подстановка — ответственность backend-developer'a,
-- функция вроде renderPageContent(slug): возвращает готовый markdown
-- с подставленными плейсхолдерами.
-- ============================================================

