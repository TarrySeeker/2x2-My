-- ------------------------------------------------------------
-- 1. Таблица
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS page_content (
  id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  path             TEXT NOT NULL UNIQUE,
  title            TEXT NOT NULL,
  content_markdown TEXT NOT NULL,
  version          INT NOT NULL DEFAULT 1,
  published        BOOLEAN NOT NULL DEFAULT true,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by       TEXT NULL
);

COMMENT ON TABLE  page_content IS 'Длинные текстовые страницы (политика, оферта, terms). Markdown. Плейсхолдеры вида {legal_name} подставляются из site_settings.legal_entity.';
COMMENT ON COLUMN page_content.version IS 'Инкрементируется сервер-экшеном при каждом сохранении. Можно показывать клиенту «версия N».';
COMMENT ON COLUMN page_content.published IS 'Если false — страница возвращает notFound().';

-- ------------------------------------------------------------
-- 2. Индексы
-- ------------------------------------------------------------
-- UNIQUE(path) уже создаёт индекс.
CREATE INDEX IF NOT EXISTS idx_page_content_published
  ON page_content(published) WHERE published = true;

-- ------------------------------------------------------------
-- 3. Триггер updated_at
-- ------------------------------------------------------------
DROP TRIGGER IF EXISTS tr_page_content_updated ON page_content;
CREATE TRIGGER tr_page_content_updated
  BEFORE UPDATE ON page_content
  FOR EACH ROW EXECUTE FUNCTION trg_update_updated_at();

