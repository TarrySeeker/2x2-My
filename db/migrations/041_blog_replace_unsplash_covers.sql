-- ============================================================
-- 041_blog_replace_unsplash_covers.sql
-- Очистить cover_image_url у блог-постов, ссылающихся на Unsplash
-- ============================================================
-- Зачем. Сидовые посты (миграции 014, 015) использовали URL'ы
-- images.unsplash.com как обложки-плейсхолдеры. У клиента «2х2»
-- после деплоя на VPS обложки то и дело не отображаются:
--   • сторонний домен — лишний DNS+TLS hop;
--   • Roskomnadzor / корп.файрволы клиентских организаций
--     иногда блокируют unsplash.com;
--   • если фото удалят / переместят — на сайте «битая» картинка
--     без какой-либо индикации;
--   • при `unoptimized` next/image грузил их на клиенте напрямую
--     — никакого кэша на нашей стороне.
--
-- Архитектурное решение. Если cover_image_url — это Unsplash, обнуляем
-- (NULL → пустая строка). Серверный рендер `app/blog/page.tsx` сам
-- подставит локальный SVG-плейсхолдер `/img/placeholders/blog-default.svg`
-- (см. FALLBACK_COVER в коде).
--
-- Контент клиента (он сам через админку загрузит реальные обложки)
-- мы НЕ трогаем — фильтр строгий по префиксу `https://images.unsplash.com/`.
--
-- Идемпотентность: WHERE по префиксу — повторный прогон не трогает
-- уже очищенные строки.
-- ============================================================

BEGIN;

UPDATE blog_posts
   SET cover_image_url = '',
       updated_at = NOW()
 WHERE cover_image_url LIKE 'https://images.unsplash.com/%';

COMMIT;
